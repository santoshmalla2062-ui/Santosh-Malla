import { AppState, StaffRole } from '../types';
import { ActiveTab } from '../components/Navigation';
import { parseOrderTimestampMs } from '../utils/timeUtils';
import { isInternalArchivalOrder, isSameLocalCalendarDay } from './orderAudit';

export type NotificationCategory = 
  | 'INVENTORY' 
  | 'KITCHEN' 
  | 'RESERVATION' 
  | 'HOUSEKEEPING' 
  | 'FINANCE' 
  | 'SECURITY' 
  | 'SYSTEM';

export type NotificationSeverity = 'info' | 'warning' | 'alert' | 'success';

export interface AppNotification {
  id: string;
  businessId: string;
  category: NotificationCategory;
  title: string;
  message: string;
  timestamp: string;
  isRead: boolean;
  severity: NotificationSeverity;
  targetTab?: ActiveTab;
  targetAction?: string;
  autoGenerated?: boolean;
}

/**
 * Loads stored manual / persisted notifications for the business.
 */
export function getStoredNotifications(businessId: string): AppNotification[] {
  try {
    const key = `himalayan_notifications_${businessId}`;
    const raw = localStorage.getItem(key);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (err) {
    console.warn('[NotificationService] Error reading notifications:', err);
  }
  return [];
}

/**
 * Saves notifications for a specific tenant business.
 */
export function saveStoredNotifications(businessId: string, notifications: AppNotification[]): void {
  try {
    const key = `himalayan_notifications_${businessId}`;
    // Keep at most 100 historical notifications
    const trimmed = notifications.slice(0, 100);
    localStorage.setItem(key, JSON.stringify(trimmed));
  } catch (err) {
    console.warn('[NotificationService] Error saving notifications:', err);
  }
}

export function markNotificationAsRead(businessId: string, notificationId: string, currentNotifications: AppNotification[]): void {
  const stored = getStoredNotifications(businessId);
  const byId = new Map<string, AppNotification>();
  stored.forEach((n) => byId.set(n.id, n));
  const target = currentNotifications.find((n) => n.id === notificationId);
  if (target) {
    byId.set(notificationId, { ...target, isRead: true });
  } else if (byId.has(notificationId)) {
    byId.set(notificationId, { ...byId.get(notificationId)!, isRead: true });
  }
  saveStoredNotifications(businessId, Array.from(byId.values()));
}

export function markAllNotificationsAsRead(businessId: string, currentNotifications: AppNotification[]): void {
  const stored = getStoredNotifications(businessId);
  const byId = new Map<string, AppNotification>();
  stored.forEach((n) => byId.set(n.id, { ...n, isRead: true }));
  currentNotifications.forEach((n) => byId.set(n.id, { ...n, isRead: true }));
  saveStoredNotifications(businessId, Array.from(byId.values()));
}

/**
 * Smart Workflow Automation Engine:
 * Analyzes the current live state of the business and generates intelligent, role-relevant notifications.
 * Automatically de-duplicates with already stored notifications.
 */
export function generateSmartNotifications(appState: AppState, businessId: string): AppNotification[] {
  const generated: AppNotification[] = [];
  const now = new Date();
  const todayStr = now.toISOString().slice(0, 10);
  const timestamp = now.toISOString().replace('T', ' ').slice(0, 19);

  // 1. INVENTORY AUTOMATION: Low Stock Detection
  if (appState.inventoryItems && appState.inventoryItems.length > 0) {
    const lowStockItems = appState.inventoryItems.filter(item => item.currentStock <= item.minStockAlert);
    if (lowStockItems.length > 0) {
      const topItems = lowStockItems.slice(0, 3).map(i => `${i.name} (${i.currentStock} ${i.unit})`).join(', ');
      generated.push({
        id: `auto-low-stock-${todayStr}-${lowStockItems.length}`,
        businessId,
        category: 'INVENTORY',
        title: `${lowStockItems.length} Items Running Low on Stock`,
        message: `Inventory alert: ${topItems}${lowStockItems.length > 3 ? ` and ${lowStockItems.length - 3} more` : ''}. Review reorder levels immediately.`,
        timestamp,
        isRead: false,
        severity: 'warning',
        targetTab: 'inventory',
        autoGenerated: true
      });
    }
  }

  // 2. KITCHEN AUTOMATION: Ready Dishes Waiting for Waiter & Urgent Orders & Cancelled Orders
  if (appState.orders && appState.orders.length > 0) {
    const readyOrders = appState.orders.filter(o => o.status === 'active' && o.kotStatus === 'ready');
    if (readyOrders.length > 0) {
      const tables = readyOrders.map(o => o.tableRoomName || `Token #${o.kotNo}`).join(', ');
      generated.push({
        id: `auto-kds-ready-${readyOrders.length}`,
        businessId,
        category: 'KITCHEN',
        title: `${readyOrders.length} Kitchen Order(s) Ready to Serve!`,
        message: `Food ready for table: ${tables}. Please dispatch waiters for prompt delivery.`,
        timestamp,
        isRead: false,
        severity: 'success',
        targetTab: 'kds',
        autoGenerated: true
      });
    }

    // Check for tickets unaccepted for >15 min
    const urgentOrders = appState.orders.filter(o => {
      if (o.status === 'active' && (o.kotStatus === 'sent_to_kitchen' || !o.kotStatus)) {
        const refMs = parseOrderTimestampMs(o.kotSentAt || o.createdAt);
        return refMs > 0 && Date.now() - refMs > 15 * 60 * 1000;
      }
      return false;
    });

    if (urgentOrders.length > 0) {
      generated.push({
        id: `auto-kds-urgent-${urgentOrders.length}`,
        businessId,
        category: 'KITCHEN',
        title: `Kitchen Attention: ${urgentOrders.length} Pending Order(s) > 15 Min`,
        message: `Tickets waiting acceptance for over 15 minutes. Ensure chef acknowledges orders to avoid auto-expiration.`,
        timestamp,
        isRead: false,
        severity: 'alert',
        targetTab: 'kds',
        autoGenerated: true
      });
    }

    // Voided / Cancelled orders today alert for Admin/Manager
    const cancelledToday = appState.orders.filter((o) => {
      if (isInternalArchivalOrder(o)) return false;
      const isCancelled = o.status === 'cancelled' || (o.status === 'active' && o.kotStatus === 'cancelled');
      if (!isCancelled) return false;
      const ms = parseOrderTimestampMs(o.voidedAt || o.createdAt);
      return isSameLocalCalendarDay(ms, now);
    });

    if (cancelledToday.length > 0) {
      const cancelledVal = cancelledToday.reduce((sum, o) => sum + (Number(o.grandTotal) || 0), 0);
      const currency = appState.settings?.currencySymbol || 'Rs.';
      generated.push({
        id: `auto-fin-cancelled-${todayStr}-${cancelledToday.length}`,
        businessId,
        category: 'FINANCE',
        title: `${cancelledToday.length} Cancelled Order(s) Today (${currency} ${cancelledVal.toLocaleString()})`,
        message: `Latest void reason: ${cancelledToday[0]?.voidReason || 'Order cancelled'}. Inspect today's order ledger for audit details.`,
        timestamp,
        isRead: false,
        severity: 'alert',
        targetTab: 'reports',
        autoGenerated: true
      });
    }
  }

  // 3. RESERVATION AUTOMATION: Arrivals & Departures Today
  if (appState.reservations && appState.reservations.length > 0) {
    const todayArrivals = appState.reservations.filter(r => 
      r.status === 'CONFIRMED' && r.checkInDate.startsWith(todayStr)
    );
    if (todayArrivals.length > 0) {
      generated.push({
        id: `auto-res-arrivals-${todayStr}-${todayArrivals.length}`,
        businessId,
        category: 'RESERVATION',
        title: `${todayArrivals.length} Guest Arrival(s) Scheduled Today`,
        message: `Guests expected: ${todayArrivals.map(r => r.guestName).join(', ')}. Prepare room keys and check registration cards.`,
        timestamp,
        isRead: false,
        severity: 'info',
        targetTab: 'resort',
        autoGenerated: true
      });
    }

    const todayDepartures = appState.reservations.filter(r => 
      r.status === 'CHECKED_IN' && r.checkOutDate.startsWith(todayStr)
    );
    if (todayDepartures.length > 0) {
      generated.push({
        id: `auto-res-departures-${todayStr}-${todayDepartures.length}`,
        businessId,
        category: 'RESERVATION',
        title: `${todayDepartures.length} Guest Check-out(s) Scheduled Today`,
        message: `Rooms due for settlement: ${todayDepartures.map(r => r.guestName).join(', ')}. Audit minibar and settle room folios.`,
        timestamp,
        isRead: false,
        severity: 'info',
        targetTab: 'resort',
        autoGenerated: true
      });
    }
  }

  // 4. HOUSEKEEPING AUTOMATION: Dirty Rooms Pending Cleaning
  if (appState.resortRooms && appState.resortRooms.length > 0) {
    const dirtyRooms = appState.resortRooms.filter(r => r.status === 'DIRTY' || r.status === 'CLEANING');
    if (dirtyRooms.length > 0) {
      generated.push({
        id: `auto-hk-dirty-${dirtyRooms.length}`,
        businessId,
        category: 'HOUSEKEEPING',
        title: `${dirtyRooms.length} Room(s) Require Housekeeping`,
        message: `Rooms: ${dirtyRooms.map(r => r.roomNumber).join(', ')}. Housekeeping tasks need completion prior to guest check-in.`,
        timestamp,
        isRead: false,
        severity: 'warning',
        targetTab: 'resort',
        autoGenerated: true
      });
    }
  }

  // 5. FINANCE AUTOMATION: High Khata Balance Dues
  if (appState.customers && appState.customers.length > 0) {
    const highDueCustomers = appState.customers.filter(c => (c.creditBalance || 0) > 5000);
    if (highDueCustomers.length > 0) {
      generated.push({
        id: `auto-fin-khata-${todayStr}-${highDueCustomers.length}`,
        businessId,
        category: 'FINANCE',
        title: `${highDueCustomers.length} Customer(s) with Khata Credit > Rs. 5,000`,
        message: `Outstanding balances: ${highDueCustomers.slice(0, 2).map(c => `${c.name} (Rs. ${c.creditBalance.toLocaleString()})`).join(', ')}. Send payment reminder receipts.`,
        timestamp,
        isRead: false,
        severity: 'info',
        targetTab: 'customers',
        autoGenerated: true
      });
    }
  }

  // 6. DAY CLOSING AUTOMATION: Evening Closing Reminder
  const currentHour = now.getHours();
  if (currentHour >= 20 || currentHour < 4) {
    const closingToday = appState.dayClosings?.find(dc => dc.date === todayStr);
    if (!closingToday) {
      generated.push({
        id: `auto-fin-closing-${todayStr}`,
        businessId,
        category: 'FINANCE',
        title: 'Daily Register Closing Pending',
        message: `End-of-day operations reminder: Cash closing and drawer reconciliation for ${todayStr} has not been completed.`,
        timestamp,
        isRead: false,
        severity: 'warning',
        targetTab: 'day_closing',
        autoGenerated: true
      });
    }
  }

  return generated;
}

/**
 * Merges stored notifications with live generated notifications,
 * preserving read states and avoiding duplicates.
 */
export function getConsolidatedNotifications(
  appState: AppState,
  businessId: string,
  userRole?: StaffRole
): AppNotification[] {
  const stored = getStoredNotifications(businessId);
  const smart = generateSmartNotifications(appState, businessId);

  // Map of read states by ID
  const readStateMap = new Map<string, boolean>();
  stored.forEach(n => readStateMap.set(n.id, n.isRead));

  // Merge
  const mergedMap = new Map<string, AppNotification>();

  // Add smart notifications (keeping read state if previously marked read)
  smart.forEach(n => {
    if (readStateMap.has(n.id)) {
      n.isRead = readStateMap.get(n.id)!;
    }
    mergedMap.set(n.id, n);
  });

  // Add stored non-smart notifications
  stored.forEach(n => {
    if (!n.autoGenerated && !mergedMap.has(n.id)) {
      mergedMap.set(n.id, n);
    }
  });

  const all = Array.from(mergedMap.values());

  // Sort descending by timestamp / urgency
  all.sort((a, b) => {
    if (a.isRead !== b.isRead) return a.isRead ? 1 : -1;
    return new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime();
  });

  // Filter based on user role if specified
  if (!userRole || userRole === 'SUPER_ADMIN' || userRole === 'OWNER' || userRole === 'ADMIN' || userRole === 'MANAGER') {
    return all;
  }

  const roleCategoriesMap: Record<StaffRole, NotificationCategory[]> = {
    CASHIER: ['FINANCE', 'KITCHEN', 'SYSTEM'],
    WAITER: ['KITCHEN', 'SYSTEM'],
    KITCHEN: ['KITCHEN', 'SYSTEM'],
    RECEPTIONIST: ['RESERVATION', 'HOUSEKEEPING', 'FINANCE', 'SYSTEM'],
    HOUSEKEEPING: ['HOUSEKEEPING', 'SYSTEM'],
    INVENTORY_STAFF: ['INVENTORY', 'SYSTEM'],
    ACCOUNTANT: ['FINANCE', 'SYSTEM'],
    STAFF: ['SYSTEM'],
    MANAGER: ['INVENTORY', 'KITCHEN', 'RESERVATION', 'HOUSEKEEPING', 'FINANCE', 'SECURITY', 'SYSTEM'],
    ADMIN: ['INVENTORY', 'KITCHEN', 'RESERVATION', 'HOUSEKEEPING', 'FINANCE', 'SECURITY', 'SYSTEM'],
    OWNER: ['INVENTORY', 'KITCHEN', 'RESERVATION', 'HOUSEKEEPING', 'FINANCE', 'SECURITY', 'SYSTEM'],
    SUPER_ADMIN: ['INVENTORY', 'KITCHEN', 'RESERVATION', 'HOUSEKEEPING', 'FINANCE', 'SECURITY', 'SYSTEM']
  };

  const allowedCategories = roleCategoriesMap[userRole] || ['SYSTEM'];
  return all.filter(n => allowedCategories.includes(n.category));
}
